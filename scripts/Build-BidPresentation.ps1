#Requires -Version 7.0
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$sample = Join-Path $root 'samples/02-bid-review-queue'
$data = Join-Path $sample 'src/BidReviewQueue/Data'
$item = (Get-Content (Join-Path $data 'sample-bid-form.json') -Raw | ConvertFrom-Json).items | Where-Object number -eq '13'
if (@($item).Count -ne 1) { throw 'Expected exactly one synthetic item 13.' }

function Read-Recording([string]$name) {
    $matches = @(Get-Content (Join-Path $data "recordings/$name") |
        ForEach-Object { $_ | ConvertFrom-Json } |
        Where-Object { $_.description -eq $item.description -and $_.unit -eq $item.unit -and !$_.reverseOptions })
    if ($matches.Count -ne 1) { throw "Expected one default-order item 13 recording in $name." }
    return $matches[0]
}

$decision = Read-Recording 'demo-run.jsonl'
$second = Read-Recording 'escalation-demo-run.jsonl'
$answers = ($decision.response | ConvertFrom-Json -AsHashtable).answers
$secondBody = $second.response | ConvertFrom-Json
if ($secondBody.status -ne 'completed') { throw 'The recorded second opinion did not complete.' }
$content = @($secondBody.output | Where-Object type -eq 'message' | ForEach-Object { $_.content })
if ($content | Where-Object type -eq 'refusal') { throw 'The recorded second opinion refused.' }
$text = ($content | Where-Object type -eq 'output_text' | ForEach-Object { $_.text }) -join ''
$choices = $text | ConvertFrom-Json -AsHashtable
if ($answers.Count -ne 2 -or $choices.Count -ne 2) { throw 'This guide expects the two taxonomy questions for item 13.' }
$projected = foreach ($name in 'system', 'work_type') {
    $answer = $answers[$name]
    if (!$answer -or $answer.type -ne 'choice' -or !$answer.probabilities.Contains($answer.choice) -or !$answer.probabilities.Contains($choices[$name])) {
        throw "Invalid recorded choice for $name."
    }
    [ordered]@{ name = $name; choice = $answer.choice; probabilities = $answer.probabilities; secondChoice = $choices[$name] }
}
$payload = [ordered]@{
    number = $item.number
    description = $item.description
    unit = $item.unit
    decisionRecordedAt = ([datetime]$decision.recordedAtUtc).ToUniversalTime().ToString('o', [Globalization.CultureInfo]::InvariantCulture)
    secondOpinionRecordedAt = ([datetime]$second.recordedAtUtc).ToUniversalTime().ToString('o', [Globalization.CultureInfo]::InvariantCulture)
    model = $decision.model
    secondModel = $second.model
    answers = @($projected)
}
$json = ConvertTo-Json -InputObject $payload -Depth 12 -EscapeHandling EscapeHtml
$generated = "// Generated by scripts/Build-BidPresentation.ps1 from the bundled synthetic recordings.`n`"use strict`";`nglobalThis.bidReviewCase = $json;`n"
$generated = $generated.Replace("`r`n", "`n")
$destination = Join-Path $root 'docs/site/labs/002/case-data.js'
if ($Check) {
    if (!(Test-Path $destination) -or [IO.File]::ReadAllText($destination).Replace("`r`n", "`n") -cne $generated) {
        throw 'The static presentation data is out of date. Run scripts/Build-BidPresentation.ps1.'
    }
    Write-Output 'PASS: Presentation data matches the bundled item 13 recordings'
} else {
    [IO.File]::WriteAllText($destination, $generated)
}
